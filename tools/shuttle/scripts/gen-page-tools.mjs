// Expands config/agent-browser-tools.json into the fork's page_tools_data.inc
// (a C++ raw string with minified JSON). Usage:
//   node scripts/gen-page-tools.mjs [out.inc]   (default: stdout; --stats prints sizes)
import fs from 'node:fs';
const cfg = JSON.parse(fs.readFileSync(new URL('../config/agent-browser-tools.json', import.meta.url)));
const tools = cfg.tools.map(t => {
  const props = { ...cfg.common, ...t.props };
  const ab = {};
  if (t.ab) ab.tool = t.ab;
  if (t.variants) ab.variants = t.variants;
  for (const k of ['map', 'fixed', 'special']) if (t[k]) ab[k] = t[k];
  return { name: t.name, description: t.description, ab,
    inputSchema: { type: 'object', properties: props, required: ['targetId', ...(t.required || [])] } };
});
const json = JSON.stringify(tools);
const listBytes = JSON.stringify(tools.map(({ ab, ...r }) => r)).length;
if (process.argv.includes('--stats')) {
  console.error(`tools: ${tools.length}, tools/list bytes: ${listBytes} (~${Math.round(listBytes / 4)} tokens), full incl. mapping: ${json.length}`);
}
const out = `// Generated by scripts/gen-page-tools.mjs from config/agent-browser-tools.json. Do not edit.\nR"AC_JSON(${json})AC_JSON"\n`;
const dst = process.argv.slice(2).find(a => !a.startsWith('--'));
if (dst) fs.writeFileSync(dst, out); else process.stdout.write(out);
